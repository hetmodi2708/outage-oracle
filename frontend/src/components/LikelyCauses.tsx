import ReactMarkdown from 'react-markdown'

interface LikelyCausesProps {
  markdown: string
  confidence: number
}

// Thresholds are on the best chunk's cosine similarity.
// The backend already rejects anything below 0.42 (see retrieval/generate.py).
function matchStrength(confidence: number) {
  if (confidence >= 0.6) return { label: 'Strong match', level: 'strong' }
  if (confidence >= 0.5) return { label: 'Good match', level: 'strong' }
  return { label: 'Partial match', level: 'moderate' }
}

// Turn the LLM's citations like [1] into links that jump to the matching incident card
function linkCitations(markdown: string) {
  return markdown.replace(/\[(\d+)\](?!\()/g, '[[$1]](#incident-$1)')
}

export function LikelyCauses({ markdown, confidence }: LikelyCausesProps) {
  const strength = matchStrength(confidence)

  return (
    <section className="panel" aria-labelledby="causes-heading">
      <header className="panel__header">
        <h2 id="causes-heading">Likely causes</h2>
        <span
          className={`badge badge--${strength.level}`}
          title={`Best passage similarity: ${confidence.toFixed(2)}`}
        >
          {strength.label}
        </span>
      </header>
      <div className="markdown">
        <ReactMarkdown>{linkCitations(markdown)}</ReactMarkdown>
      </div>
      <p className="panel__note">
        Generated by an LLM from the incidents below. Treat it as a starting point and verify before acting.
      </p>
    </section>
  )
}
